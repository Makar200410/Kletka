      s += box(x0, cy, dw, H, 'c5 thin ' + (it[2] || 'f1'), 8) + lay(x0, cy + (H - 30) / 2, dw, it[0], null, it[3]).s;
      s += box(x0 + dw + 6, cy, tw, H, 'c5 thin fs', 8) + b.s;
